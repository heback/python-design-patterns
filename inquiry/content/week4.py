OBS = '''
class Feed:
    def __init__(self): self.subs = []
    def subscribe(self, f): self.subs.append(f)
    def push(self, p):
        for f in self.subs:
            f(p)

feed = Feed()
log = []

def once(p):
    log.append(("once", p))
    feed.subs.remove(once)               # 한 번 받고 스스로 구독 해제

feed.subscribe(once)
feed.subscribe(lambda p: log.append(("b", p)))
feed.push(1)
feed.push(2)
print(log)
'''

